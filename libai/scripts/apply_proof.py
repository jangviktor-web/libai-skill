def main():
    lines = open(PATH, encoding='utf-8').read().split('\n')
    ok = bad = 0
    for ln, old, new in EDITS:
        s = lines[ln - 1]
        if old not in s:
            print(f'!! 未找到 L{ln}: {old}  实际: {s.strip()}')
            bad += 1
            continue
        if s.count(old) > 1:
            print(f'!! 不唯一 L{ln}: {old}')
            bad += 1
            continue
        lines[ln - 1] = s.replace(old, new)
        ok += 1
    open(PATH, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'完成: 应用 {ok} 条, 失败 {bad} 条')

if __name__ == '__main__':
    main()
